import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = new URL('../client.js', import.meta.url);
const { outputFiles: [bundle] } = await build({
  absWorkingDir: root,
  entryPoints: ['web/entry.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  write: false,
  minifyWhitespace: true,
});
const source = `// Generated by npm run build from web/ and locale/.\n${bundle.text}`;

if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== source) {
    throw new Error('client.js is stale. Run npm run build and include the regenerated bundle.');
  }
} else {
  await writeFile(output, source, 'utf8');
}
