/**
 * A local Markdown wiki store.
 *
 * The knowledge-wiki quickstart keeps its pages in a managed memory store. DSH
 * has no such service, so this class provides the same user-visible shape over
 * the local filesystem: `_index.md` at the root, `SKILL.md`, one page per file,
 * `[[slug]]` links and inline provenance citations. It is deliberately read-only
 * for the model: only the build pipeline writes here.
 *
 * The store is also used for the memory representation (via a second root) when
 * dream needs link/index validation, while the existing MemoryStore keeps
 * owning memory file semantics and atomic writes.
 */
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import {
  DEFAULT_MAX_PAGE_BYTES,
  WIKI_GENERATIONS_DIR,
  WIKI_GENERATION_NAME,
  WIKI_INDEX_NAME,
  WIKI_PAGE_RE,
  WIKI_RESERVED,
  WIKI_SKILL_NAME,
  buildIndex,
  buildSkill,
  claimId,
  extractCitations,
  extractLinks,
  fileSlug,
  oneLine,
  pageMeta,
  parsePage,
  renderPage,
  slugify,
  stripCode,
  validatePage,
} from './wiki-core.js';

const INDEX_MARKER = '<!-- generated by dsh-cc-dream-memory -->';
const FACT_CITATION_RE = /\^\[[^\]\n]*\]/g;
const LIST_MARKER_RE = /^\s*(?:[-*+]|\d+[.)])\s+/;

function errorMessage(error) {
  return error && typeof error === 'object' && error.message ? String(error.message) : String(error);
}

function isMissing(error) {
  return error && error.code === 'ENOENT';
}

/**
 * Name of the generation the wiki root points at, or `''` for a legacy layout.
 * A pointer that names a missing directory is ignored, so a torn publish can
 * never strand the readers on a half-written generation.
 */
function readGenerationPointer(rootDir) {
  let raw = '';
  try {
    raw = fsSync.readFileSync(path.join(rootDir, WIKI_GENERATION_NAME), 'utf8').trim();
  } catch {
    return '';
  }
  if (!/^[\w.-]{1,120}$/u.test(raw)) return '';
  try {
    return fsSync.statSync(path.join(rootDir, WIKI_GENERATIONS_DIR, raw)).isDirectory() ? raw : '';
  } catch {
    return '';
  }
}

/** Readers pinned to a generation keep it alive until they close. */
const openGenerations = new Map();
const generationReaper = typeof FinalizationRegistry === 'function'
  ? new FinalizationRegistry((key) => releaseGenerationKey(key))
  : null;

function retainGeneration(dir) {
  const key = path.resolve(dir);
  openGenerations.set(key, (openGenerations.get(key) ?? 0) + 1);
  return key;
}

function releaseGenerationKey(key) {
  const count = openGenerations.get(key) ?? 0;
  if (count <= 1) {
    openGenerations.delete(key);
    return;
  }
  openGenerations.set(key, count - 1);
}

/**
 * Content root for a wiki root: the generation `GENERATION` points at, or the
 * root itself for a legacy layout.
 *
 * @param {string} rootDir
 * @returns {string}
 */
export function resolveWikiContentDir(rootDir) {
  const generation = readGenerationPointer(rootDir);
  return generation === '' ? rootDir : path.join(rootDir, WIKI_GENERATIONS_DIR, generation);
}

/**
 * Index file a reader should open for a wiki root.
 *
 * @param {string} rootDir
 * @returns {string}
 */
export function resolveWikiIndexFile(rootDir) {
  return path.join(resolveWikiContentDir(rootDir), WIKI_INDEX_NAME);
}

/**
 * True while at least one reader still holds this generation open.
 *
 * @param {string} dir generation directory.
 * @returns {boolean}
 */
export function isGenerationOpen(dir) {
  return openGenerations.has(path.resolve(dir));
}

/** Words and CJK bigrams, the same cheap surface used elsewhere in the plugin. */
export function searchTokens(text) {
  const tokens = new Set();
  const value = String(text ?? '').toLowerCase();
  for (const word of value.match(/[a-z][a-z0-9]{2,}/g) ?? []) tokens.add(word);
  for (const run of value.match(/[\u3400-\u9fff]{2,}/g) ?? []) {
    for (let i = 0; i + 2 <= run.length; i += 1) tokens.add(run.slice(i, i + 2));
  }
  return tokens;
}

/**
 * Derive fact-level claims from the sourced fact lines of one page body.
 *
 * A sourced fact line is a line carrying `^[source#locator, date]` (all three
 * parts present). The claim id is a deterministic hash of the page, the source
 * location and the normalized fact text, so it is stable across reads and
 * rebuilds as long as the fact line does not change. Citation tokens, list
 * markers and fenced/inline code are not part of the claim text.
 *
 * @param {string} body page body (without frontmatter)
 * @param {{file?:string}} [options]
 * @returns {Array<{claimId:string,text:string,source:string,locator:string,date:string}>}
 */
export function extractFactClaims(body, { file = '' } = {}) {
  const claims = [];
  const seen = new Set();
  const page = String(file ?? '');
  const text = stripCode(String(body ?? '')).replace(/\r\n?/g, '\n');
  for (const line of text.split('\n')) {
    const citations = extractCitations(line).filter(
      (citation) => citation.source !== '' && citation.locator !== '' && citation.date !== '',
    );
    if (citations.length === 0) continue;
    const statement = oneLine(line.replace(FACT_CITATION_RE, ' ').replace(LIST_MARKER_RE, ''));
    if (statement === '') continue;
    for (const citation of citations) {
      const id = claimId(
        `${page}\u0000${citation.source}\u0000${citation.locator}\u0000${citation.date}\u0000${statement}`,
      );
      if (seen.has(id)) continue;
      seen.add(id);
      claims.push({
        claimId: id,
        text: statement,
        source: citation.source,
        locator: citation.locator,
        date: citation.date,
      });
    }
  }
  return claims;
}

/**
 * Attach the matching fact claim id to page-level citations.
 * @param {Array<object>} citations citations from `pageMeta()`
 * @param {Array<object>} claims claims from `extractFactClaims()`
 * @returns {Array<object>}
 */
export function claimsForCitations(citations, claims) {
  const list = Array.isArray(citations) ? citations : [];
  const pool = Array.isArray(claims) ? claims : [];
  return list.map((citation) => {
    const item = citation && typeof citation === 'object' ? citation : {};
    const match = pool.find(
      (claim) => claim.source === item.source && claim.locator === item.locator && claim.date === item.date,
    );
    return match ? { ...item, claimId: match.claimId } : { ...item };
  });
}

/**
 * @param {{rootDir:string, maxPageBytes?:number, config?:object}} options
 */
export class WikiStore {
  constructor({ rootDir, maxPageBytes = DEFAULT_MAX_PAGE_BYTES, config } = {}) {
    this.rootDir = path.resolve(String(rootDir ?? ''));
    // Pages, sources, index and skill belong to the generation the `GENERATION`
    // pointer names. The root itself only holds the pointer, the build manifests
    // and the generations, so a reader never mixes two publishes.
    this.generation = readGenerationPointer(this.rootDir);
    this.contentDir = this.generation === ''
      ? this.rootDir
      : path.join(this.rootDir, WIKI_GENERATIONS_DIR, this.generation);
    // A reader that opened a generation keeps it from being pruned underneath
    // it; the pointer already keeps new readers off an old generation.
    this._generationKey = '';
    if (this.generation !== '') {
      this._generationKey = retainGeneration(this.contentDir);
      this._generationToken = {};
      generationReaper?.register(this._generationToken, this._generationKey);
    }
    this.indexFile = path.join(this.contentDir, WIKI_INDEX_NAME);
    this.skillFile = path.join(this.contentDir, WIKI_SKILL_NAME);
    this.sourcesDir = path.join(this.contentDir, '.sources');
    this.buildsDir = path.join(this.rootDir, '.builds');
    this.maxPageBytes = Number.isFinite(Number(maxPageBytes)) && Number(maxPageBytes) > 0
      ? Math.trunc(Number(maxPageBytes))
      : DEFAULT_MAX_PAGE_BYTES;
    this.config = config && typeof config === 'object' ? config : {};
  }

  /** Release the generation this reader pinned. Safe to call twice. */
  close() {
    if (this._generationKey === '') return;
    generationReaper?.unregister(this._generationToken);
    releaseGenerationKey(this._generationKey);
    this._generationKey = '';
  }

  /** Create the root and an empty index. Idempotent. */
  async ensure() {
    await fs.mkdir(this.rootDir, { recursive: true });
    try {
      await fs.access(this.indexFile);
    } catch (error) {
      if (!isMissing(error)) throw error;
      await this._atomicWrite(this.indexFile, `${INDEX_MARKER}\n\n`);
    }
  }

  /** Absolute path of one page, refusing traversal and reserved names. */
  pagePath(file) {
    const name = String(file ?? '');
    if (!WIKI_PAGE_RE.test(name) || WIKI_RESERVED.has(name) || name.includes('..')) {
      throw new Error(`unsafe wiki page name: ${name || '(empty)'}`);
    }
    return path.join(this.contentDir, name);
  }

  /** List every page with parsed metadata. Missing root counts as empty. */
  async listPages() {
    let names = [];
    try {
      names = await fs.readdir(this.contentDir);
    } catch (error) {
      if (isMissing(error)) return [];
      throw error;
    }
    const pages = [];
    for (const file of names.sort()) {
      if (!WIKI_PAGE_RE.test(file) || WIKI_RESERVED.has(file)) continue;
      try {
        const raw = await fs.readFile(path.join(this.contentDir, file), 'utf8');
        pages.push(pageMeta({ file, ...parsePage(raw), raw }));
      } catch (error) {
        if (isMissing(error)) continue;
        throw error;
      }
    }
    return pages;
  }

  /**
   * Read one page; returns the parsed frontmatter, body, claim ids and raw text.
   * `claims` is `[{claimId,text,source,locator,date}]`; `citations` carries the
   * matching `claimId` where one exists.
   */
  async readPage(file) {
    const target = this.pagePath(file);
    const raw = await fs.readFile(target, 'utf8');
    const parsed = parsePage(raw);
    const name = path.basename(target);
    const meta = pageMeta({ file: name, ...parsed, raw });
    const claims = extractFactClaims(parsed.body, { file: name });
    return {
      file: name,
      ...parsed,
      ...meta,
      citations: claimsForCitations(meta.citations, claims),
      claims,
    };
  }

  /**
   * Write one page atomically. `page` may be a raw string or a renderPage input.
   * The index is not updated here; the build/organizer owns that.
   */
  async writePage(file, page, { maxBytes = this.maxPageBytes } = {}) {
    const name = String(file ?? '');
    const target = this.pagePath(name);
    let text;
    if (typeof page === 'string') {
      text = page;
    } else {
      const { file: _pageFile, ...pageData } = page && typeof page === 'object' ? page : {};
      text = renderPage(pageData);
    }
    const validation = validatePage({ file: name, text, maxBytes });
    if (!validation.ok) throw new Error(`invalid wiki page ${name}: ${validation.errors.join('; ')}`);
    await fs.mkdir(this.contentDir, { recursive: true });
    await this._atomicWrite(target, text);
    return { file: name, bytes: Buffer.byteLength(text, 'utf8'), warnings: validation.warnings };
  }

  /** Remove one page. */
  async deletePage(file) {
    const target = this.pagePath(file);
    try {
      await fs.unlink(target);
      return true;
    } catch (error) {
      if (isMissing(error)) return false;
      throw error;
    }
  }

  /** Rename one page and return the old/new slugs for link rewriting. */
  async movePage(from, to) {
    const source = this.pagePath(from);
    const target = this.pagePath(to);
    const text = await fs.readFile(source, 'utf8');
    const parsed = parsePage(text);
    const next = renderPage({
      ...parsed.data,
      body: parsed.body,
      extra: parsed.data,
    });
    await this._atomicWrite(target, next);
    await fs.unlink(source);
    return { from: fileSlug(from), to: fileSlug(to) };
  }

  /** Read the index; missing returns an empty document. */
  async readIndex() {
    try {
      return await fs.readFile(this.indexFile, 'utf8');
    } catch (error) {
      if (isMissing(error)) return '';
      throw error;
    }
  }

  /** Replace the index atomically. */
  async writeIndex(text) {
    const content = String(text ?? '').replace(/\r\n?/g, '\n');
    const payload = content.endsWith('\n') ? content : `${content}\n`;
    await fs.mkdir(this.contentDir, { recursive: true });
    await this._atomicWrite(this.indexFile, payload);
    return { file: WIKI_INDEX_NAME, bytes: Buffer.byteLength(payload, 'utf8') };
  }

  /** Read SKILL.md; missing returns an empty string. */
  async readSkill() {
    try {
      return await fs.readFile(this.skillFile, 'utf8');
    } catch (error) {
      if (isMissing(error)) return '';
      throw error;
    }
  }

  /** Replace SKILL.md atomically. */
  async writeSkill(text) {
    const content = String(text ?? '').replace(/\r\n?/g, '\n');
    const payload = content.endsWith('\n') ? content : `${content}\n`;
    await fs.mkdir(this.contentDir, { recursive: true });
    await this._atomicWrite(this.skillFile, payload);
    return { file: WIKI_SKILL_NAME, bytes: Buffer.byteLength(payload, 'utf8') };
  }

  /** Build a complete index from the current pages. */
  async rebuildIndex({ title = '', groupBy = 'domain', style = 'wiki' } = {}) {
    const pages = await this.listPages();
    const text = buildIndex({ pages, style, title, groupBy });
    await this.writeIndex(text);
    return { pages: pages.length, text };
  }

  /** Build a usage skill from the current pages. */
  async rebuildSkill({ title = 'Knowledge wiki', description = '', style = 'wiki' } = {}) {
    const pages = await this.listPages();
    const domains = [...new Set(pages.map((page) => page.domain).filter(Boolean))].sort();
    const text = buildSkill({ title, description, domains, style });
    await this.writeSkill(text);
    return { pages: pages.length, domains, text };
  }

  /**
   * Pages whose body contains a link to `slug`.
   * @returns {Promise<string[]>} backlink slugs
   */
  async backlinks(slug) {
    const wanted = slugify(slug);
    const pages = await this.listPages();
    return pages.filter((page) => page.links.includes(wanted)).map((page) => page.slug).sort();
  }

  /**
   * Lexical search over page metadata and bodies. No model call.
   * @param {string} query
   * @param {{limit?:number, maxSnippetChars?:number}} [options]
   * @returns {Promise<Array<{page:string,slug:string,name:string,description:string,score:number,
   *   snippet:string,links:string[],citations:object[]}>>}
   */
  async search(query, { limit = 5, maxSnippetChars = 500 } = {}) {
    const wanted = searchTokens(query);
    if (wanted.size === 0) return [];
    const names = await fs.readdir(this.contentDir).catch((error) => {
      if (isMissing(error)) return [];
      throw error;
    });
    const hits = [];
    for (const file of names.sort()) {
      if (!WIKI_PAGE_RE.test(file) || WIKI_RESERVED.has(file)) continue;
      const raw = await fs.readFile(path.join(this.contentDir, file), 'utf8').catch((error) => {
        if (isMissing(error)) return '';
        throw error;
      });
      if (raw === '') continue;
      const parsed = parsePage(raw);
      const meta = pageMeta({ file, ...parsed, raw });
      const claims = extractFactClaims(parsed.body, { file });
      const nameTokens = searchTokens(`${meta.name} ${meta.description}`);
      const bodyTokens = searchTokens(parsed.body);
      let score = 0;
      for (const token of wanted) {
        if (nameTokens.has(token)) score += 5;
        if (bodyTokens.has(token)) score += 1;
      }
      if (score <= 0) continue;
      const body = parsed.body;
      let snippet = '';
      const lower = body.toLowerCase();
      for (const token of wanted) {
        const at = lower.indexOf(token);
        if (at >= 0) {
          const start = Math.max(0, at - Math.floor(maxSnippetChars / 3));
          snippet = body.slice(start, start + maxSnippetChars).replace(/\s+/g, ' ').trim();
          break;
        }
      }
      hits.push({
        page: file,
        slug: meta.slug,
        name: meta.name,
        description: meta.description,
        score,
        snippet: snippet || meta.description || body.slice(0, maxSnippetChars).replace(/\s+/g, ' ').trim(),
        links: meta.links,
        citations: claimsForCitations(meta.citations, claims),
        claims,
      });
    }
    return hits.sort((a, b) => b.score - a.score || a.page.localeCompare(b.page)).slice(0, Math.max(1, limit));
  }

  /**
   * Validate the whole wiki: dangling links, index coverage and oversized pages.
   * @returns {Promise<{ok:boolean, pages:number, missing:string[], dangling:Array<{from:string,to:string}>,
   *   indexMissing:string[], indexDangling:string[], oversized:Array<{file:string,bytes:number}>}>}
   */
  async audit({ maxBytes = this.maxPageBytes } = {}) {
    const pages = await this.listPages();
    const slugs = new Set(pages.map((page) => page.slug));
    const dangling = [];
    for (const page of pages) {
      for (const link of page.links) {
        if (!slugs.has(link)) dangling.push({ from: page.file, to: link });
      }
    }
    const index = await this.readIndex();
    const indexed = new Set();
    for (const match of index.matchAll(/\[\[([^\]\n|]+)(?:\|[^\]\n]*)?\]\]/g)) indexed.add(slugify(match[1]));
    for (const match of index.matchAll(/\[[^\]]*\]\(([^)]+\.md)\)/g)) indexed.add(fileSlug(match[1]));
    const indexMissing = pages.filter((page) => !indexed.has(page.slug)).map((page) => page.file);
    const indexDangling = [...indexed].filter((slug) => !slugs.has(slug));
    const oversized = pages.filter((page) => page.bytes > maxBytes).map((page) => ({ file: page.file, bytes: page.bytes }));
    return {
      ok: dangling.length === 0 && indexMissing.length === 0 && indexDangling.length === 0 && oversized.length === 0,
      pages: pages.length,
      missing: [...new Set(dangling.map((item) => item.to))].sort(),
      dangling,
      indexMissing,
      indexDangling,
      oversized,
    };
  }

  /** Store one normalized source document for a knowledge-wiki build. */
  async writeSource(sourceId, text, meta = {}) {
    const id = slugify(sourceId);
    await fs.mkdir(this.sourcesDir, { recursive: true });
    await this._atomicWrite(path.join(this.sourcesDir, `${id}.txt`), String(text ?? ''));
    await this._atomicWrite(
      path.join(this.sourcesDir, `${id}.json`),
      `${JSON.stringify({ ...meta, sourceId: id, sha256: createHash('sha256').update(String(text ?? '')).digest('hex') }, null, 2)}\n`,
    );
    return id;
  }

  /** Read one stored source document. */
  async readSource(sourceId) {
    const id = slugify(sourceId);
    const text = await fs.readFile(path.join(this.sourcesDir, `${id}.txt`), 'utf8');
    let meta = {};
    try {
      meta = JSON.parse(await fs.readFile(path.join(this.sourcesDir, `${id}.json`), 'utf8'));
    } catch (error) {
      if (!isMissing(error)) throw error;
    }
    return { sourceId: id, text, meta };
  }

  /** List stored source ids. */
  async listSources() {
    try {
      const names = await fs.readdir(this.sourcesDir);
      return names.filter((name) => name.endsWith('.txt')).map((name) => name.replace(/\.txt$/i, '')).sort();
    } catch (error) {
      if (isMissing(error)) return [];
      throw error;
    }
  }

  /** Write one build manifest under `.builds/<ts>/manifest.json`. */
  async writeBuildManifest(runId, manifest) {
    const dir = path.join(this.buildsDir, String(runId));
    await fs.mkdir(dir, { recursive: true });
    await this._atomicWrite(path.join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    return path.join(dir, 'manifest.json');
  }

  /** Read the newest build manifest, or `undefined`. */
  async latestBuildManifest() {
    let dirs = [];
    try {
      dirs = (await fs.readdir(this.buildsDir)).sort();
    } catch (error) {
      if (isMissing(error)) return undefined;
      throw error;
    }
    for (const dir of dirs.reverse()) {
      try {
        const raw = await fs.readFile(path.join(this.buildsDir, dir, 'manifest.json'), 'utf8');
        return JSON.parse(raw);
      } catch (error) {
        if (!isMissing(error)) throw error;
      }
    }
    return undefined;
  }

  /** Atomic write: temp file in the same directory, then rename. */
  async _atomicWrite(target, content) {
    await fs.mkdir(path.dirname(target), { recursive: true });
    const temporary = `${target}.tmp-${process.pid}-${Math.random().toString(36).slice(2, 8)}`;
    await fs.writeFile(temporary, String(content ?? ''), 'utf8');
    try {
      await fs.rename(temporary, target);
    } catch (error) {
      await fs.unlink(temporary).catch(() => {});
      throw new Error(`could not write ${path.basename(target)}: ${errorMessage(error)}`);
    }
  }
}
